package box3;

public class Num10to1 {

	public static void main(String[] args) {
		for(int i=10;i>=1;i--)
		{
			System.out.println(i);
		}
       System.out.println(".............");  
       //print -10 to 0
       for(int i =-10 ;i<=0;i++)
       {
    	   System.out.println(i);
       }
       System.out.println("...............");
      // print -20 to -30
       for(int i=-20 ; i>=-30 ; i--)
       {
    	   System.out.println(i);
       }
       System.out.println("...............");
 
	}

}
