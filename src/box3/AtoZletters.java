package box3;

public class AtoZletters {

	public static void main(String[] args) {
		for(char ch='A';ch<='Z';ch++) {
			System.out.println(ch);
		}
		System.out.println("....................");
		
		for(char ch='A';ch<='Z';ch++) {
			System.out.print(ch+"  ");
		}
		System.out.println("..");
		System.out.println("....................");
		
		for(char ch=65;ch<=90;ch++) {
			System.out.println(ch+"  ");
		}
	}
	}


