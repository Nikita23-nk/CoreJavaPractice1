package box4;

public class Swapwithtemp {

	public static void main(String[] args) {
		// WAJP to swap two numbers with temporary variable
		
		int a = 320;
		int b = 450;
		
		int temp = a;
	     a = b;
	     b = temp;
	    
	    System.out.println("A value is "+a);
	    System.out.println("B value is "+b);

	}

}
