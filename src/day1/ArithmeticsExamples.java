public class ArithmeticsExamples {
	public static void main(String[] args) {
		int a = 24;
		int b = 9;
		
		int c = a + b;
		System.out.println(c +" = Addition");
		
		int d = a - b;
		System.out.println(d+" = substraction" );
		
		int e = a * b;
		System.out.println(e+ " = multiplication");
		
		int f = a / b ;
		System.out.println(f+ " = division");
	}

}
