package selfstudyoops;

class Acer{
	Acer(){           //Constructor
		System.out.println("Inside Acer Constructor");
	}
}
public class ConstructorAcer {
	public static void main(String[] args) {
		System.out.println("Main Start");
		Acer a1 = new Acer();
		System.out.println(".........");
		Acer a2 = new Acer();
		System.out.println(".........");
		Acer a3 = new Acer();
		System.out.println(".........");
		System.out.println("Main Start");
	}

}
